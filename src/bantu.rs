/// Cari nama builtin atau fungsi `std/` yang memuat `kata`.
pub fn cari(kata: &str) -> Vec<String> {
    let k = kata.to_lowercase();
    let mut v: Vec<String> = SINTAKS.iter()
        .map(|i| i.nama.to_string())
        .filter(|n| n.to_lowercase().contains(&k))
        .chain(crate::vm::daftar_builtin()
        .into_iter()
        .filter(|n| n.to_lowercase().contains(&k)))
        .chain(crate::interpreter::stdlib_src::fungsi_publik()
        .into_iter()
        .map(|f| f.nama)
        .filter(|n| n.to_lowercase().contains(&k)))
        .collect();
    v.sort();
    v.dedup();
    v
}

/// Semua nama di sebuah namespace (`str`, `arr`, `dok`, …).
pub fn daftar_namespace(ns: &str) -> Vec<String> {
    let awalan = format!("{}::", ns);
    let mut v: Vec<String> = crate::vm::daftar_builtin()
        .into_iter()
        .filter(|n| n.starts_with(&awalan))
        .collect();
    v.sort();
    v
}

/// Namespace yang ada, dengan jumlah anggotanya.
pub fn namespace_tersedia() -> Vec<(String, usize)> {
    use std::collections::BTreeMap;
    let mut m: BTreeMap<String, usize> = BTreeMap::new();
    for n in crate::vm::daftar_builtin() {
        if let Some((ns, _)) = n.split_once("::") {
            *m.entry(ns.to_string()).or_insert(0) += 1;
        }
    }
    m.into_iter().collect()
}

/// Penjelasan satu nama, siap dicetak.
pub fn jelaskan(nama: &str) -> Option<String> {
    // Bentuk sintaks lebih dulu: `for` dan `match` bukan builtin, jadi
    // pemeriksaan registry di bawah tidak akan pernah menemukannya.
    if let Some(i) = SINTAKS.iter().find(|i| i.nama == nama) {
        return Some(format!("{}\n  {}", i.tanda_tangan, i.ringkas));
    }
    // Fungsi modul `std/`: 106 di antaranya tadinya tidak bisa dijelaskan sama
    // sekali — `--doc iterator::map` menjawab "tidak terdaftar" untuk sesuatu
    // yang jelas ada. Daftarnya diturunkan dari sumber yang tertanam.
    if let Some(f) = crate::interpreter::stdlib_src::fungsi_publik()
        .into_iter().find(|f| f.nama == nama)
    {
        let ringkas = if f.ringkas.is_empty() {
            "(belum ada penjelasan tertulis untuk nama ini)".to_string()
        } else {
            f.ringkas.clone()
        };
        return Some(format!(
            "{}::{}\n  {}\n  butuh: import \"std/{}\"",
            f.namespace, f.tanda_tangan, ringkas, f.modul));
    }
    let terdaftar = crate::vm::ada_builtin(nama);
    if !terdaftar {
        return None;
    }
    if let Some(i) = DOKUMEN.iter().find(|i| i.nama == nama) {
        return Some(format!("{}\n  {}", i.tanda_tangan, i.ringkas));
    }
    // Belum dijelaskan. Yang masih bisa dikatakan dengan jujur: ia ada, dan berapa
    // argumen yang ia terima — batas yang sama yang ditegakkan pintu native.
    use crate::interpreter::arity::{maks, minimal};
    let arity = match (minimal(nama), maks(nama)) {
        (Some(b), Some(m)) if b == m => format!("butuh {} argumen", b),
        (Some(b), Some(m)) => format!("{} sampai {} argumen", b, m),
        (Some(b), None) => format!("paling sedikit {} argumen", b),
        (None, Some(m)) => format!("paling banyak {} argumen", m),
        (None, None) => "jumlah argumennya tidak dibatasi tabel".to_string(),
    };
    Some(format!(
        "{} — terdaftar, {}.\n  (belum ada penjelasan tertulis untuk nama ini)",
        nama, arity))
}
