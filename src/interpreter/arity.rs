/// Batas atas argumen untuk `nama`, kalau memang diketahui.
pub fn maks(nama: &str) -> Option<usize> {
    MAKS.binary_search_by(|(n, _)| (*n).cmp(nama)).ok().map(|i| MAKS[i].1 as usize)
}

/// Batas bawah argumen untuk `nama`: entri [`MINIMAL`], atau batas atasnya sendiri.
pub fn minimal(nama: &str) -> Option<usize> {
    MINIMAL.binary_search_by(|(n, _)| (*n).cmp(nama)).ok()
        .map(|i| MINIMAL[i].1 as usize).or_else(|| maks(nama))
}

/// Tanda tangan yang `--doc` tulis untuk `nama`, kalau ada.
pub fn tanda_tangan(nama: &str) -> Option<&'static str> {
    crate::bantu::DOKUMEN.iter().find(|i| i.nama == nama).map(|i| i.tanda_tangan)
}

/// Pemanggilan yang KURANG argumen — satu kalimat untuk pintu native dua mesin,
/// berbentuk sama dengan keluarga `math::` dan pintu method.
pub fn pesan_kurang(nama: &str, min: usize, maks: Option<usize>, diberi: usize,
                    tanda: Option<&str>) -> String {
    let jumlah = match maks {
        Some(m) if m == min => format!("{} argumen", min),
        Some(m) => format!("{} sampai {} argumen", min, m),
        None => format!("paling sedikit {} argumen", min),
    };
    let mut s = format!("`{}` butuh {}, dapat {}", nama, jumlah, diberi);
    if let Some(t) = tanda {
        s.push_str(&format!("\n  bantuan: bentuknya `{}`", t));
    }
    s
}

/// Seperti [`maks`] untuk `ns::nama`, tanpa merangkai string: dipakai pintu
/// method, yang dilewati TIAP pemanggilan method.
pub fn maks_ns(ns: &str, nama: &str) -> Option<usize> {
    type Peta<V> = std::collections::HashMap<&'static str, V, std::hash::BuildHasherDefault<Fnv>>;
    static INDEKS: std::sync::OnceLock<Peta<Peta<u8>>> = std::sync::OnceLock::new();
    let indeks = INDEKS.get_or_init(|| {
        let mut m: Peta<Peta<u8>> = Peta::default();
        for (n, k) in MAKS {
            let (ns, nama) = n.split_once("::").unwrap_or(("", n));
            m.entry(ns).or_default().insert(nama, *k);
        }
        m
    });
    indeks.get(ns)?.get(nama).map(|k| *k as usize)
}

/// FNV-1a: kunci di sini pendek dan tidak datang dari luar, jadi hash yang
/// tahan serangan (bawaan `HashMap`) cuma biaya.
#[derive(Default)]
pub(crate) struct Fnv(u64);

/// Peta ber-hasher FNV — dipakai juga pintu native dua mesin (dilewati tiap panggilan).
pub(crate) type PetaFnv<K, V> = std::collections::HashMap<K, V, std::hash::BuildHasherDefault<Fnv>>;
impl std::hash::Hasher for Fnv {
    fn write(&mut self, bytes: &[u8]) {
        let mut h = if self.0 == 0 { 0xcbf2_9ce4_8422_2325 } else { self.0 };
        for b in bytes { h ^= *b as u64; h = h.wrapping_mul(0x0000_0100_0000_01b3); }
        self.0 = h;
    }
    fn finish(&self) -> u64 { self.0 }
}

/// Pesan untuk pemanggilan yang kelebihan argumen — satu kalimat untuk parser
/// (bentuk namespace) dan pintu native dua mesin.
pub fn pesan_kebanyakan(nama: &str, maks: usize, diberi: usize) -> String {
    let bantuan = petunjuk_kebanyakan(nama, diberi).unwrap_or_else(|| format!(
        "buang {} argumen terakhir — argumen di luar batas itu tidak dipakai \
         fungsinya sama sekali", diberi - maks));
    format!("`{}` kebanyakan argumen: paling banyak {}, diberi {}\n  bantuan: {}",
        nama, maks, diberi, bantuan)
}

/// Argumen lebih yang BERARTI sesuatu di bahasa lain, dan dulu dibuang diam-diam
/// sehingga jawabannya salah tanpa suara. Tiap jalan keluar di sini sudah dijalankan.
fn petunjuk_kebanyakan(nama: &str, diberi: usize) -> Option<String> {
    Some(match (nama, diberi) {
        ("parse_int" | "str::to_int", 2) => format!(
            "`{}` selalu membaca basis 10 — ia tidak punya argumen basis seperti \
             `parseInt(s, 2)` di JavaScript; untuk basis lain pakai \
             `dok::num_from_base(teks, basis)`", nama),
        ("int" | "uint", 2) => format!(
            "`{0}(x)` sama dengan `x as {0}` dan cuma menerima satu nilai; kalau yang \
             dimaksud basis bilangan seperti `int(s, 2)` di Python, pakai \
             `dok::num_from_base(teks, basis)`", nama),
        ("enumerate" | "arr::enumerate", 2) => format!(
            "`{}` selalu mulai dari 0 — ia tidak punya argumen awal seperti \
             `enumerate(a, 1)` di Python; untuk mulai dari 1, pakai `for i, x in a` \
             lalu tulis `i + 1`", nama),
        ("range", _) => format!("`range` menerima {}", crate::interpreter::BENTUK_RANGE),
        ("zip" | "arr::zip", n) if n >= 3 => format!(
            "`{}` memasangkan tepat DUA array; untuk lebih, pakai indeks: \
             `for i, x in a {{ … b[i] … c[i] }}`", nama),
        _ => return None,
    })
}

#[cfg(test)]
mod tes {
    /// Daftarnya harus TERURUT, karena [`super::maks`] mencarinya biner.
    #[test]
    fn daftar_terurut_dan_tidak_ganda() {
        for w in super::MAKS.windows(2) {
            assert!(w[0].0 < w[1].0,
                "daftar arity tidak terurut (atau ada nama ganda): `{}` sesudah `{}`",
                w[1].0, w[0].0);
        }
    }

    /// Tiap nama di daftar harus bisa ditemukan kembali oleh `maks`.
    #[test]
    fn tiap_nama_bisa_ditemukan() {
        for (n, v) in super::MAKS {
            assert_eq!(super::maks(n), Some(*v as usize), "`{}` tidak ketemu lagi", n);
        }
    }

    /// `MINIMAL` juga dicari biner, dan batas bawah tidak boleh melampaui batas atas.
    #[test]
    fn minimal_terurut_dan_tidak_melampaui_maks() {
        for w in super::MINIMAL.windows(2) {
            assert!(w[0].0 < w[1].0, "MINIMAL tidak terurut: `{}` sesudah `{}`", w[1].0, w[0].0);
        }
        for (n, v) in super::MINIMAL {
            assert_eq!(super::minimal(n), Some(*v as usize), "`{}` tidak ketemu lagi", n);
            if let Some(m) = super::maks(n) {
                assert!((*v as usize) < m, "`{}`: batas bawah {} tidak lebih kecil dari batas atas {} \
                    — entrinya berlebih atau salah", n, v, m);
            }
        }
    }

    /// Tanda tangan `--doc` menyebut parameter yang SAMA dengan yang ditegakkan pintu:
    /// yang wajib = batas bawah, seluruhnya = batas atas. Pesan "kurang argumen"
    /// mengutip tanda tangannya, jadi dua sumber untuk satu bentuk harus sepakat.
    #[test]
    fn tanda_tangan_dok_sepakat_dengan_batas() {
        let mut salah = Vec::new();
        let mut diperiksa = 0;
        for i in crate::bantu::DOKUMEN {
            if !crate::vm::ada_builtin(i.nama) { continue; }
            let Some((wajib, total)) = urai_tanda_tangan(i.tanda_tangan) else { continue };
            diperiksa += 1;
            if let Some(b) = super::minimal(i.nama).filter(|b| *b != wajib) {
                salah.push(format!("`{}`: dok mewajibkan {}, batas bawah {} — {}", i.nama, wajib, b, i.tanda_tangan));
            }
            match (super::maks(i.nama), total) {
                (Some(m), Some(t)) if m != t => salah.push(format!(
                    "`{}`: dok menyebut {} parameter, batas atas {} — {}", i.nama, t, m, i.tanda_tangan)),
                (Some(m), None) => salah.push(format!(
                    "`{}`: dok variadik, batas atas {} — {}", i.nama, m, i.tanda_tangan)),
                _ => {}
            }
        }
        assert!(diperiksa > 250, "cuma {} tanda tangan yang terurai — sapuannya menyusut", diperiksa);
        assert!(salah.is_empty(), "{} tanda tangan tidak sepakat:\n{}", salah.len(), salah.join("\n"));
    }

    /// (jumlah parameter wajib, jumlah seluruhnya — `None` kalau variadik). Alternatif
    /// yang dipisah `|` digabung: wajibnya yang terkecil, seluruhnya yang terbesar.
    fn urai_tanda_tangan(t: &str) -> Option<(usize, Option<usize>)> {
        let (mut wajib, mut total) = (usize::MAX, Some(0usize));
        for alt in t.split('|') {
            let kepala = alt.split(" -> ").next()?;
            let isi = kepala.split_once('(')?.1.rsplit_once(')')?.0;
            let ps: Vec<&str> = isi.split(',').map(str::trim).filter(|p| !p.is_empty()).collect();
            let opsional = |p: &&str| p.split(':').next().unwrap_or("").trim().ends_with('?');
            let w = ps.iter().filter(|p| !opsional(p) && !p.starts_with("...")).count();
            wajib = wajib.min(w);
            total = match (total, ps.iter().any(|p| p.starts_with("..."))) {
                (Some(t), false) => Some(t.max(ps.len())),
                _ => None,
            };
        }
        Some((wajib, total))
    }

    /// `maks_ns` harus menjawab persis `maks` untuk tiap nama berpemisah —
    /// perbandingan byte-nya tidak boleh berselisih dengan urutan tabelnya.
    #[test]
    fn maks_ns_sama_dengan_maks() {
        let mut diperiksa = 0;
        for (n, v) in super::MAKS {
            let (ns, nama) = n.split_once("::").unwrap_or(("", n));
            assert_eq!(super::maks_ns(ns, nama), Some(*v as usize), "`{}`", n);
            diperiksa += 1;
        }
        assert!(diperiksa > 400, "cuma {} nama diperiksa", diperiksa);
        assert_eq!(super::maks_ns("arr", "tidak_ada"), None);
        assert_eq!(super::maks_ns("ar", "r::take"), None);
    }
}
